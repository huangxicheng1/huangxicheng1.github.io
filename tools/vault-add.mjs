#!/usr/bin/env node
/**
 * 追加新笔记到「笔记库」的加密正文（不重建封存室）。
 * ---------------------------------------------------------------------------
 * 为什么不直接用 tools/vault-build.mjs：
 *   它会 rmSync(vault/enc/) 后整体重写，而封存室是"一个 salt、一把钥匙"的整体包
 *   （vault/data.js 存全部明文的密文）。如果本机没有 _private/（明文源 + pass.txt），
 *   直接重建会把已有加密笔记一起抹掉。
 *
 * 本脚本只做两件事：
 *   1) 用**现有** vault/enc.js 里的 salt 与迭代次数派生同一把钥匙，把新笔记正文
 *      加密成 vault/enc/<id>.js；
 *   2) 把新条目追加进 vault/enc.js 的 meta / files。
 *   已有条目与已有密文文件一个字节都不动；vault/data.js（封存室）也不动。
 *
 * 用法：
 *   node tools/vault-add.mjs                      # 把 _private 里所有新笔记加进去
 *   node tools/vault-add.mjs notes/2026-11-13-rag # 只加指定 id
 *   node tools/vault-add.mjs --pass "口令"         # 口令临时传入（不落盘）
 *   node tools/vault-add.mjs --self-test          # 离线自检，不需要真实口令
 */
import { createCipheriv, createDecipheriv, pbkdf2Sync, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadNotes } from "./vault-shared.mjs";

const ITER = 600000;
const BANNER = "// Generated by tools/vault-build.mjs — ciphertext only, safe to commit.\n";

// ---------------------------------------------------------------- 加解密

function deriveKey(password, salt, iterations) {
  return pbkdf2Sync(password, salt, iterations, 32, "sha256");
}

function seal(text, key) {
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const body = Buffer.concat([cipher.update(text, "utf8"), cipher.final()]);
  return { iv: iv.toString("base64"), ct: Buffer.concat([body, cipher.getAuthTag()]).toString("base64") };
}

function readSecretNotes(file) {
  const src = readFileSync(file, "utf8");
  const start = src.indexOf("window.SECRET_NOTES");
  if (start < 0) throw new Error("vault/enc.js 里没有 window.SECRET_NOTES");
  const brace = src.indexOf("{", start);
  const end = src.lastIndexOf("}");
  return JSON.parse(src.slice(brace, end + 1));
}

function writeSecretNotes(file, data) {
  writeFileSync(file, BANNER + "window.SECRET_NOTES = " + JSON.stringify(data) + ";\n", "utf8");
}

function fileNameFor(id) {
  return id.replace(/[\\/]+/g, "__").replace(/[^\w.\-]/g, "") + ".js";
}

// ---------------------------------------------------------------- 主流程

function resolvePassword(root) {
  const flag = process.argv.indexOf("--pass");
  if (flag > -1 && process.argv[flag + 1]) return process.argv[flag + 1];
  if (process.env.VAULT_PASS) return process.env.VAULT_PASS;
  const passFile = join(root, "_private", "pass.txt");
  if (existsSync(passFile)) {
    const saved = readFileSync(passFile, "utf8").trim();
    if (saved) return saved;
  }
  throw new Error(
    "没有口令。三选一：\n" +
    "  · 把原来的 _private/pass.txt 放回项目里（推荐，和已有笔记同一把钥匙）\n" +
    "  · node tools/vault-add.mjs --pass \"你的口令\"\n" +
    "  · 设置环境变量 VAULT_PASS"
  );
}

export function addNotes(root, password, wantedId) {
  const encFile = join(root, "vault", "enc.js");
  const encDir = join(root, "vault", "enc");
  if (!existsSync(encFile)) throw new Error("找不到 vault/enc.js —— 这个仓库还没建过封存室？");

  const secret = readSecretNotes(encFile);
  const salt = Buffer.from(secret.salt, "base64");
  if (salt.length !== 16) throw new Error("enc.js 里的 salt 不是 16 字节，格式不对");
  const key = deriveKey(password, salt, secret.iter || ITER);

  const notes = loadNotes(join(root, "_private"));
  if (!notes.length) throw new Error("_private/ 里没有 .md 笔记");

  const existing = new Set(secret.meta.map(m => m.id));
  const targets = notes.filter(n => n.visibility !== "vault")          // vault 级只进封存室，本脚本不处理
    .filter(n => (wantedId ? n.id === wantedId : true))
    .filter(n => wantedId || !existing.has(n.id));                     // 默认只加新的

  if (!targets.length) {
    console.log("· 没有需要新增的笔记（_private 里的都已在 enc.js 中）");
    return { added: 0 };
  }

  mkdirSync(encDir, { recursive: true });
  for (const note of targets) {
    const body = seal(JSON.stringify({ content: note.content }), key);
    const name = fileNameFor(note.id);
    writeFileSync(
      join(encDir, name),
      "window.SECRET_BODIES = window.SECRET_BODIES || {};\n" +
        "window.SECRET_BODIES[" + JSON.stringify(note.id) + "] = " + JSON.stringify(body) + ";\n",
      "utf8"
    );

    const meta = {
      id: note.id, title: note.title, date: note.date, type: note.type,
      category: note.category, summary: note.summary, tags: note.tags, review: note.review
    };
    const at = secret.meta.findIndex(m => m.id === note.id);
    if (at >= 0) secret.meta[at] = meta; else secret.meta.push(meta);
    secret.files[note.id] = "vault/enc/" + name;
    console.log(`  + ${note.date}  ${note.title}  [${note.category}]  tags=${note.tags.join(",")}  ${(Buffer.byteLength(note.content) / 1024).toFixed(1)} KB`);
  }

  // 按日期倒序，和 vault-build 的排序保持一致
  secret.meta.sort((a, b) => (a.date === b.date ? a.id.localeCompare(b.id) : a.date < b.date ? 1 : -1));
  secret.built = new Date().toISOString();
  writeSecretNotes(encFile, secret);
  return { added: targets.length };
}

// ---------------------------------------------------------------- 自检

function runSelfTest() {
  const tmp = mkdtempSync(join(tmpdir(), "vault-add-"));
  const vault = join(tmp, "vault");
  const notes = join(tmp, "_private", "notes");
  mkdirSync(join(vault, "enc"), { recursive: true });
  mkdirSync(notes, { recursive: true });

  const password = "self-test-passphrase";
  const salt = randomBytes(16);
  const key = deriveKey(password, salt, ITER);

  // 造一条"已有"笔记
  const oldId = "notes/2020-01-01-old";
  const oldBody = seal(JSON.stringify({ content: "旧的加密笔记正文" }), key);
  writeFileSync(join(vault, "enc", fileNameFor(oldId)),
    "window.SECRET_BODIES = window.SECRET_BODIES || {};\n" +
    "window.SECRET_BODIES[" + JSON.stringify(oldId) + "] = " + JSON.stringify(oldBody) + ";\n", "utf8");

  const oldSecret = {
    v: 1, kdf: "PBKDF2-SHA256", iter: ITER, salt: salt.toString("base64"),
    meta: [{ id: oldId, title: "旧笔记", date: "2020-01-01", type: "note", category: "测试", summary: "", tags: [], review: "" }],
    files: { [oldId]: "vault/enc/" + fileNameFor(oldId) }, built: "2020-01-01T00:00:00.000Z"
  };
  writeSecretNotes(join(vault, "enc.js"), oldSecret);

  // 造一条新笔记（用真实 front matter 格式）
  writeFileSync(join(notes, "2026-11-13-rag.md"),
    "---\ntitle: RAG 综合梳理（重点）\ndate: 2026-11-13\ntype: note\ncategory: agent\n" +
    "summary: 测试用摘要\ntags: RAG\nreview: 2026-11-20\nvisibility: locked\n---\n\n# 正文\n\nRAG 是先检索再生成。\n", "utf8");

  const before = readFileSync(join(vault, "enc", fileNameFor(oldId)), "utf8");
  const result = addNotes(tmp, password, "notes/2026-11-13-rag");
  const after = readFileSync(join(vault, "enc", fileNameFor(oldId)), "utf8");
  const merged = readSecretNotes(join(vault, "enc.js"));

  const checks = [];
  checks.push(["新增 1 篇", result.added === 1]);
  checks.push(["旧密文未被改动", before === after]);
  checks.push(["meta 变成 2 条", merged.meta.length === 2]);
  checks.push(["files 变成 2 条", Object.keys(merged.files).length === 2]);
  checks.push(["新笔记 category=agent", merged.meta.find(m => m.id.includes("rag"))?.category === "agent"]);
  checks.push(["新笔记 tags=[RAG]", JSON.stringify(merged.meta.find(m => m.id.includes("rag"))?.tags) === '["RAG"]']);

    // 用同一把钥匙把新密文解开，验证内容一致
  const newFile = readFileSync(join(vault, "enc", fileNameFor("notes/2026-11-13-rag")), "utf8");
  const sealedBody = JSON.parse(newFile.slice(newFile.indexOf("=", newFile.indexOf("]")) + 1).trim().replace(/;$/, ""));
  const decipher = createDecipherivSync(key, Buffer.from(sealedBody.iv, "base64"), sealedBody.ct);
  const plain = JSON.parse(decipher);
  checks.push(["能解回正文", plain.content.includes("RAG 是先检索再生成")]);

  console.log("自检项：");
  let bad = 0;
  for (const [name, ok] of checks) {
    console.log(`  ${ok ? "✓" : "✗"} ${name}`);
    if (!ok) bad++;
  }
  rmSync(tmp, { recursive: true, force: true });
  console.log(bad === 0 ? "\n全部通过：追加模式不会破坏已有笔记。" : `\n有 ${bad} 项失败`);
  process.exit(bad === 0 ? 0 : 1);
}

// 不依赖额外库的 GCM 解密（tag 拼在密文尾部）
function createDecipherivSync(key, iv, ctB64) {
  const raw = Buffer.from(ctB64, "base64");
  const tag = raw.subarray(raw.length - 16);
  const ct = raw.subarray(0, raw.length - 16);
  const d = createDecipheriv("aes-256-gcm", key, iv);
  d.setAuthTag(tag);
  return Buffer.concat([d.update(ct), d.final()]).toString("utf8");
}

// ---------------------------------------------------------------- 入口

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
if (process.argv.includes("--self-test")) {
  runSelfTest();
} else {
  const idArg = process.argv.slice(2).find(a => !a.startsWith("--") && process.argv[process.argv.indexOf(a) - 1] !== "--pass");
  const password = resolvePassword(ROOT);
  console.log("· 使用现有 enc.js 的 salt 派生钥匙（不重建封存室）");
  console.log(`  注意：vault/data.js（封存室整包）不会更新，新笔记只出现在笔记库`);
  const r = addNotes(ROOT, password, idArg);
  if (r.added) console.log(`· 完成，新增 ${r.added} 篇。记得提交 vault/enc.js 与 vault/enc/`);
}
