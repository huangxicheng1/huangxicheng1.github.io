#!/usr/bin/env node
/**
 * 封存室构建器
 * ---------------------------------------------------------------------------
 * 把 _private/ 里的私密笔记加密成 vault/data.js，供 GitHub Pages 上的
 * /vault/ 页面在浏览器本地解密查看。
 *
 * 明文只留在本机：_private/ 已被 .gitignore 排除，仓库里只会留下密文。
 * 算法：PBKDF2-SHA256(600k) 派生密钥 + AES-256-GCM，仅用 node:crypto，零依赖。
 *
 * 用法：
 *   node tools/vault-build.mjs                 # 用 _private/pass.txt 里的口令
 *   node tools/vault-build.mjs --pass "xxx"    # 临时指定口令（不落盘）
 *
 * 注意：口令丢了就解不回来，脚本不会也无法帮你恢复。
 */
import { createCipheriv, pbkdf2Sync, randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadNotes } from "./vault-shared.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PRIVATE = join(ROOT, "_private");
const VAULT = join(ROOT, "vault");
const OUT = join(VAULT, "data.js");
const PASS_FILE = join(PRIVATE, "pass.txt");
const ITERATIONS = 600000;

function readPassword() {
  const flag = process.argv.indexOf("--pass");
  if (flag > -1 && process.argv[flag + 1]) return process.argv[flag + 1];
  if (process.env.VAULT_PASS) return process.env.VAULT_PASS;
  if (existsSync(PASS_FILE)) {
    const saved = readFileSync(PASS_FILE, "utf8").trim();
    if (saved) return saved;
  }
  mkdirSync(PRIVATE, { recursive: true });
  const generated = randomBytes(12).toString("base64url");
  writeFileSync(PASS_FILE, generated + "\n", "utf8");
  console.log("· 没有找到口令，已生成一个并写入 _private/pass.txt");
  console.log("  口令：" + generated);
  return generated;
}

function encrypt(payload, password) {
  const salt = randomBytes(16);
  const iv = randomBytes(12);
  const key = pbkdf2Sync(password, salt, ITERATIONS, 32, "sha256");
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const ciphertext = Buffer.concat([cipher.update(JSON.stringify(payload), "utf8"), cipher.final()]);
  const sealed = Buffer.concat([ciphertext, cipher.getAuthTag()]);
  return {
    v: 1,
    kdf: "PBKDF2-SHA256",
    iter: ITERATIONS,
    salt: salt.toString("base64"),
    iv: iv.toString("base64"),
    ct: sealed.toString("base64"),
    count: payload.notes.length,
    built: new Date().toISOString()
  };
}

function main() {
  const password = readPassword();
  if (password.length < 8) throw new Error("口令太短：至少 8 位，建议 16 位以上");


  const notes = loadNotes(PRIVATE);

  const blob = encrypt({ v: 1, notes }, password);
  mkdirSync(VAULT, { recursive: true });
  writeFileSync(
    OUT,
    "// Generated by tools/vault-build.mjs — ciphertext only, safe to commit.\n" +
      "window.VAULT_DATA = " + JSON.stringify(blob) + ";\n",
    "utf8"
  );

  const bytes = Buffer.byteLength(JSON.stringify(blob));
  console.log(`· 已封存 ${notes.length} 篇（${(bytes / 1024).toFixed(1)} KB 密文）-> vault/data.js`);
  for (const note of notes) console.log(`  ${note.date}  ${note.title}`);
  if (!notes.length) console.log("  （_private/ 里还没有 .md 笔记）");
  console.log("· 记得把 vault/data.js 一起提交，否则线上还是旧密文。");
}

main();
