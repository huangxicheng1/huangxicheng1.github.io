#!/usr/bin/env node
/**
 * 从「笔记库」移除一篇加密笔记（vault-add.mjs 的反向操作）。
 *
 * 做三件事，且只碰目标这一篇：
 *   1) 删掉 vault/enc/<id>.js 这个密文文件
 *   2) 从 vault/enc.js 的 meta / files 里摘掉该条目
 *   3) 其余条目一个字节都不动
 *
 * 注意：vault/data.js（封存室的整体密文包）不归它管——那个要全量重建。
 *
 * 用法：
 *   node tools/vault-remove.mjs notes/2026-11-14-attention-tower-crossencoder
 *   node tools/vault-remove.mjs --help
 *   node tools/vault-remove.mjs --self-test     # 离线自检，不需要口令
 */
import {
  existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const BANNER = "// Generated by tools/vault-build.mjs — ciphertext only, safe to commit.\n";

function readSecretNotes(file) {
  const src = readFileSync(file, "utf8");
  const start = src.indexOf("window.SECRET_NOTES");
  if (start < 0) throw new Error("enc.js 里没有 window.SECRET_NOTES");
  const brace = src.indexOf("{", start);
  return JSON.parse(src.slice(brace, src.lastIndexOf("}") + 1));
}

function writeSecretNotes(file, data) {
  writeFileSync(file, BANNER + "window.SECRET_NOTES = " + JSON.stringify(data) + ";\n", "utf8");
}

export function removeNote(root, id) {
  const encFile = join(root, "vault", "enc.js");
  if (!existsSync(encFile)) throw new Error("找不到 vault/enc.js");

  const secret = readSecretNotes(encFile);
  const before = secret.meta.length;
  const metaHit = secret.meta.find(m => m.id === id);
  const fileHit = secret.files[id];

  if (!metaHit && !fileHit) {
    console.log(`· enc.js 里没有 ${id}，无需移除`);
    return { removed: false };
  }

  secret.meta = secret.meta.filter(m => m.id !== id);
  delete secret.files[id];
  secret.built = new Date().toISOString();
  writeSecretNotes(encFile, secret);

  if (fileHit) {
    const target = join(root, fileHit);
    if (existsSync(target)) {
      rmSync(target);
      console.log(`  - 已删除密文文件 ${fileHit}`);
    } else {
      console.log(`  - 密文文件不存在，跳过 ${fileHit}`);
    }
  }
  console.log(`· 元数据 ${before} -> ${secret.meta.length} 条`);
  return { removed: true, title: metaHit?.title, file: fileHit };
}

// ---------------------------------------------------------------- 自检

function runSelfTest() {
  const tmp = mkdtempSync(join(tmpdir(), "vault-remove-"));
  const vault = join(tmp, "vault");
  mkdirSync(join(vault, "enc"), { recursive: true });

  const keep = "notes/keep-me";
  const drop = "notes/drop-me";
  writeFileSync(join(vault, "enc", "notes__keep-me.js"), "window.SECRET_BODIES={};\n", "utf8");
  writeFileSync(join(vault, "enc", "notes__drop-me.js"), "window.SECRET_BODIES={};\n", "utf8");
  writeSecretNotes(join(vault, "enc.js"), {
    v: 1, kdf: "PBKDF2-SHA256", iter: 600000, salt: "AAAAAAAAAAAAAAAAAAAAAA==",
    meta: [
      { id: keep, title: "保留", date: "2020-01-01", tags: [] },
      { id: drop, title: "删除", date: "2020-01-02", tags: [] },
    ],
    files: { [keep]: "vault/enc/notes__keep-me.js", [drop]: "vault/enc/notes__drop-me.js" },
    built: "2020-01-01T00:00:00.000Z",
  });

  const keepBefore = readFileSync(join(vault, "enc", "notes__keep-me.js"), "utf8");
  removeNote(tmp, drop);
  const after = readSecretNotes(join(vault, "enc.js"));
  const keepAfter = readFileSync(join(vault, "enc", "notes__keep-me.js"), "utf8");

  const checks = [
    ["目标条目已移除", !after.meta.some(m => m.id === drop)],
    ["目标密文文件已删除", !existsSync(join(vault, "enc", "notes__drop-me.js"))],
    ["其余条目保留", after.meta.some(m => m.id === keep)],
    ["其余密文未改动", keepBefore === keepAfter],
    ["files 同步减少", Object.keys(after.files).length === 1],
  ];
  console.log("自检项：");
  let bad = 0;
  for (const [name, ok] of checks) {
    console.log(`  ${ok ? "✓" : "✗"} ${name}`);
    if (!ok) bad++;
  }
  rmSync(tmp, { recursive: true, force: true });
  console.log(bad === 0 ? "\n全部通过：移除只影响目标那一篇。" : `\n有 ${bad} 项失败`);
  process.exit(bad === 0 ? 0 : 1);
}

// ---------------------------------------------------------------- 入口

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

if (process.argv.includes("--self-test")) {
  runSelfTest();
} else {
  const id = process.argv.slice(2).find(a => !a.startsWith("--"));
  if (!id) {
    console.log("用法：node tools/vault-remove.mjs <note-id>\n例如：node tools/vault-remove.mjs notes/2026-11-14-attention-tower-crossencoder");
    process.exit(1);
  }
  const r = removeNote(ROOT, id);
  if (r.removed) console.log("· 完成。记得提交 vault/enc.js 的改动与被删除的文件");
}
